def sign_p(w, l):
    n = w + l
    if n == 0: return 1.0
    k = min(w, l); return min(1.0, 2 * sum(comb(n, i) for i in range(k + 1)) / 2 ** n)
def pair_verdict(r, key, good):  # a win for x needs both orders to agree
    a, b = r["xy"].get(key), r["yx"].get(key)
    if a is None or b is None: return None
    if a == b and a in ("x", "y"): return a
    return "tie" if key == "clarity" else "same"
def load(path):
    p = ROOT / path
    return [json.loads(l) for l in p.read_text().splitlines()] if p.exists() else []
texts = {}
for f in (ROOT / "out").glob("*.json"):
    r = json.loads(f.read_text()); texts[(r["id"], r["arm"])] = r
def words(pid, arm): return len(texts[(pid, arm)]["text"].split())
def block(rows, x, y, setting):
    rs = [r for r in rows if r["x"] == x and r["y"] == y and (setting == "all" or r["setting"] == setting)]
    v = [pair_verdict(r, "clarity", True) for r in rs]; v = [t for t in v if t]
    w, l, t = v.count("x"), v.count("y"), v.count("tie")
    c = [pair_verdict(r, "completeness", True) for r in rs]; c = [t_ for t_ in c if t_]
    inc = [r["xy"]["clarity"] == "tie" or r["yx"]["clarity"] == "tie" or r["xy"]["clarity"] != r["yx"]["clarity"] for r in rs if "clarity" in r["xy"] and "clarity" in r["yx"]]
    return {"n": len(v), "w": w, "t": t, "l": l, "p": sign_p(w, l), "comp": (c.count("x"), c.count("same"), c.count("y")), "order_inconsistent": sum(inc), "rs": rs}
